"""Build the VS Code extension (highlighting for every installed ISA pack + the debugger).

    uv run piolab vscode                    # writes build/piolab-asm-<version>.vsix
    code --install-extension build/piolab-asm-<version>.vsix

Run it in your project's environment: the grammar's instruction, directive, condition and
keyword names come from every *installed* ISA pack's yaml (agreement #1: nothing is
defined in two places), and the language's file suffixes from the packs. The static
files (package.json, extension.js, ...) are package data next to this module; the
grammar and the suffix list are generated into the .vsix, which is a plain zip, so no
Node or vsce is needed.
"""

from __future__ import annotations

import json
import re
import zipfile
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
GRAMMAR = "piolab.tmLanguage.json"
STATIC = ["extension.js", "language-configuration.json", "README.md"]


def _alt(words: list[str]) -> str:
    return "|".join(re.escape(w) for w in sorted(words, key=lambda w: (-len(w), w)))


def _isas() -> list[object]:
    from piolab.isa import load_isa
    from piolab.packs import packs

    return [load_isa(p.spec) for p in packs().values()]


def _words(isas: list[object]) -> tuple[list[str], list[str], list[str], list[str]]:
    """(instructions, directive regexes, conditions, keywords) of every ISA pack."""
    ident = re.compile(r"[A-Za-z_]\w*")
    instrs: set[str] = set()
    dirs: set[str] = set()
    conds: set[str] = set()
    keys: set[str] = {"side"}
    for isa in isas:
        instrs |= set(isa.instructions)  # type: ignore[attr-defined]
        for d in isa.directives.values():  # type: ignore[attr-defined]
            if d.pattern:  # TextMate (Oniguruma) has no (?P<name>...): use plain groups
                dirs.add(re.sub(r"\(\?P<\w+>", "(?:", d.pattern.pattern.strip("^$")))
            else:
                dirs.add(re.escape(d.name))
        conds |= {c for c in isa.conditions if ident.fullmatch(c)}  # type: ignore[attr-defined]
        for spec in [*isa.instructions.values(), *isa.directives.values()]:  # type: ignore[attr-defined]
            for o in spec.operands:
                t = o.type
                vals: list[str] = list(t.values)
                if t.kind == "flag":
                    vals.append(t.word or o.name)
                for fv in t.fields.values():
                    vals += list(fv)
                keys |= {v for v in vals if ident.fullmatch(v) and v != "none"}
    return sorted(instrs), sorted(dirs), sorted(conds), sorted(keys - conds - instrs)


def _ext_alt(words: list[str]) -> str:
    return "|".join(sorted(words, key=lambda w: (-len(w), w)))


def grammar() -> dict[str, object]:
    instrs, directives, conds, keywords = _words(_isas())
    return {
        "$schema": "https://raw.githubusercontent.com/martinring/tmlanguage/master/"
                   "tmlanguage.json",
        "name": "PIOLab assembly",
        "scopeName": "source.piolab-asm",
        "comment": "Generated by `piolab vscode` from the installed ISA packs' yaml. "
                   "Do not edit.",
        "patterns": [
            {"name": "comment.line.semicolon.piolab-asm", "match": ";.*$"},
            {"name": "comment.line.double-slash.piolab-asm", "match": "//.*$"},
            {"name": "entity.name.function.label.piolab-asm",
             "match": r"^\s*[A-Za-z_]\w*(?=:)"},
            {"name": "keyword.control.directive.piolab-asm",
             "match": rf"(?<![\w.])(?:{_ext_alt(directives)})\b"},
            {"name": "keyword.other.instruction.piolab-asm",
             "match": rf"(?<![\w.])(?:{_alt(instrs)})(?![\w.])"},
            {"name": "constant.numeric.piolab-asm",
             "match": r"\b(?:0x[0-9A-Fa-f_]+|0b[01_]+|\d+(?:\.\d+)?[kM]?(?:x\d+)?)\b"},
            {"name": "variable.parameter.option.piolab-asm", "match": r"\b[A-Za-z_]\w*(?==)"},
            {"name": "support.constant.condition.piolab-asm",
             "match": rf"(?:!(?:x|y|osre)|x--|y--|x!=y|\b(?:{_alt(conds)})\b)"},
            {"name": "storage.modifier.delay.piolab-asm", "match": r"\[[^\]]*\]"},
            {"name": "support.type.keyword.piolab-asm", "match": rf"\b(?:{_alt(keywords)})\b"},
        ],
    }


def source_extensions() -> list[str]:
    from piolab.packs import packs

    return sorted({p.ext for p in packs().values()})


def render_grammar() -> str:
    return json.dumps(grammar(), indent=2) + "\n"


def package_json() -> dict[str, Any]:
    """The extension manifest, with the language's suffixes set to the installed packs'."""
    pkg: dict[str, Any] = json.loads((HERE / "package.json").read_text())
    pkg["contributes"]["languages"][0]["extensions"] = source_extensions()
    return pkg


def vsix(out: Path) -> Path:
    """Write the .vsix to `out` (a file path)."""
    pkg = package_json()
    manifest = f"""<?xml version="1.0" encoding="utf-8"?>
<PackageManifest Version="2.0.0" xmlns="http://schemas.microsoft.com/developer/vsx-schema/2011">
  <Metadata>
    <Identity Language="en-US" Id="{pkg['name']}" Version="{pkg['version']}"
              Publisher="{pkg['publisher']}" />
    <DisplayName>{pkg['displayName']}</DisplayName>
    <Description xml:space="preserve">{pkg['description']}</Description>
    <Categories>{','.join(pkg['categories'])}</Categories>
    <Properties>
      <Property Id="Microsoft.VisualStudio.Code.Engine" Value="{pkg['engines']['vscode']}" />
    </Properties>
  </Metadata>
  <Installation><InstallationTarget Id="Microsoft.VisualStudio.Code" /></Installation>
  <Dependencies />
  <Assets>
    <Asset Type="Microsoft.VisualStudio.Code.Manifest" Path="extension/package.json"
           Addressable="true" />
  </Assets>
</PackageManifest>
"""
    types = """<?xml version="1.0" encoding="utf-8"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension=".json" ContentType="application/json" />
  <Default Extension=".js" ContentType="application/javascript" />
  <Default Extension=".md" ContentType="text/markdown" />
  <Default Extension=".vsixmanifest" ContentType="text/xml" />
</Types>
"""
    out.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", types)
        z.writestr("extension.vsixmanifest", manifest)
        z.writestr("extension/package.json", json.dumps(pkg, indent=2) + "\n")
        z.writestr(f"extension/{GRAMMAR}", render_grammar())
        for f in STATIC:
            z.write(HERE / f, f"extension/{f}")
    return out


def main(argv: list[str] | None = None) -> int:
    import argparse

    ap = argparse.ArgumentParser(prog="piolab vscode",
                                 description="Build the VS Code extension for the installed "
                                 "ISA packs.")
    ap.add_argument("--out", type=Path, default=None,
                    help="directory (default: [tool.piolab] out, else build/)")
    a = ap.parse_args(argv)
    pkg = package_json()
    if a.out is None:
        from piolab.config import load

        a.out = load().out
    out = vsix(a.out / f"{pkg['name']}-{pkg['version']}.vsix")
    print(f"wrote {out} (source suffixes: {', '.join(source_extensions())})")
    print(f"install: code --install-extension {out}")
    return 0
