"""Build the PIOScope assembly VS Code extension.

    uv run python tools/vscode-pioscope/build.py          # regenerate pioscope.tmLanguage.json + .vsix
    code --install-extension tools/vscode-pioscope/pioscope-asm-0.1.0.vsix

The grammar's instruction, directive, condition and keyword names come from every ISA
pack's yaml (spec/isa/*.yaml; agreement #1: nothing is defined in two places), and the
language's file extensions from the packs' source suffixes; a test checks that the
committed grammar is current. The .vsix is a plain zip, so no Node or vsce is needed.
"""

from __future__ import annotations

import json
import re
import sys
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
GRAMMAR = HERE / "pioscope.tmLanguage.json"
FILES = ["package.json", "extension.js", "language-configuration.json", "pioscope.tmLanguage.json",
         "README.md"]


def _alt(words: list[str]) -> str:
    return "|".join(re.escape(w) for w in sorted(words, key=lambda w: (-len(w), w)))


def _isas() -> list[object]:
    sys.path.insert(0, str(ROOT))
    from pioscope.isa import load_isa
    from pioscope.packs import packs

    return [load_isa(p.spec) for p in packs().values()]


def _words(isas: list[object]) -> tuple[list[str], list[str], list[str], list[str]]:
    """(instructions, directive regexes, conditions, keywords) of every ISA pack."""
    ident = re.compile(r"[A-Za-z_]\w*")
    instrs: set[str] = set()
    dirs: set[str] = set()
    conds: set[str] = set()
    keys: set[str] = {"side"}
    for isa in isas:
        instrs |= set(isa.instructions)  # type: ignore[attr-defined]
        for d in isa.directives.values():  # type: ignore[attr-defined]
            if d.pattern:  # TextMate (Oniguruma) has no (?P<name>...): use plain groups
                dirs.add(re.sub(r"\(\?P<\w+>", "(?:", d.pattern.pattern.strip("^$")))
            else:
                dirs.add(re.escape(d.name))
        conds |= {c for c in isa.conditions if ident.fullmatch(c)}  # type: ignore[attr-defined]
        for spec in [*isa.instructions.values(), *isa.directives.values()]:  # type: ignore[attr-defined]
            for o in spec.operands:
                t = o.type
                vals: list[str] = list(t.values)
                if t.kind == "flag":
                    vals.append(t.word or o.name)
                for fv in t.fields.values():
                    vals += list(fv)
                keys |= {v for v in vals if ident.fullmatch(v) and v != "none"}
    return sorted(instrs), sorted(dirs), sorted(conds), sorted(keys - conds - instrs)


def _ext_alt(words: list[str]) -> str:
    return "|".join(sorted(words, key=lambda w: (-len(w), w)))


def grammar() -> dict[str, object]:
    instrs, directives, conds, keywords = _words(_isas())
    return {
        "$schema": "https://raw.githubusercontent.com/martinring/tmlanguage/master/"
                   "tmlanguage.json",
        "name": "PIOScope assembly",
        "scopeName": "source.pioscope-asm",
        "comment": "Generated by tools/vscode-pioscope/build.py from the ISA packs' yaml "
                   "(spec/isa/*.yaml). Do not edit.",
        "patterns": [
            {"name": "comment.line.semicolon.pioscope-asm", "match": ";.*$"},
            {"name": "comment.line.double-slash.pioscope-asm", "match": "//.*$"},
            {"name": "entity.name.function.label.pioscope-asm",
             "match": r"^\s*[A-Za-z_]\w*(?=:)"},
            {"name": "keyword.control.directive.pioscope-asm",
             "match": rf"(?<![\w.])(?:{_ext_alt(directives)})\b"},
            {"name": "keyword.other.instruction.pioscope-asm",
             "match": rf"(?<![\w.])(?:{_alt(instrs)})(?![\w.])"},
            {"name": "constant.numeric.pioscope-asm",
             "match": r"\b(?:0x[0-9A-Fa-f_]+|0b[01_]+|\d+(?:\.\d+)?[kM]?(?:x\d+)?)\b"},
            {"name": "variable.parameter.option.pioscope-asm", "match": r"\b[A-Za-z_]\w*(?==)"},
            {"name": "support.constant.condition.pioscope-asm",
             "match": rf"(?:!(?:x|y|osre)|x--|y--|x!=y|\b(?:{_alt(conds)})\b)"},
            {"name": "storage.modifier.delay.pioscope-asm", "match": r"\[[^\]]*\]"},
            {"name": "support.type.keyword.pioscope-asm", "match": rf"\b(?:{_alt(keywords)})\b"},
        ],
    }


def source_extensions() -> list[str]:
    sys.path.insert(0, str(ROOT))
    from pioscope.packs import packs

    return sorted({p.ext for p in packs().values()})


def render_grammar() -> str:
    return json.dumps(grammar(), indent=2) + "\n"


def vsix(out: Path) -> Path:
    pkg = json.loads((HERE / "package.json").read_text())
    manifest = f"""<?xml version="1.0" encoding="utf-8"?>
<PackageManifest Version="2.0.0" xmlns="http://schemas.microsoft.com/developer/vsx-schema/2011">
  <Metadata>
    <Identity Language="en-US" Id="{pkg['name']}" Version="{pkg['version']}"
              Publisher="{pkg['publisher']}" />
    <DisplayName>{pkg['displayName']}</DisplayName>
    <Description xml:space="preserve">{pkg['description']}</Description>
    <Categories>{','.join(pkg['categories'])}</Categories>
    <Properties>
      <Property Id="Microsoft.VisualStudio.Code.Engine" Value="{pkg['engines']['vscode']}" />
    </Properties>
  </Metadata>
  <Installation><InstallationTarget Id="Microsoft.VisualStudio.Code" /></Installation>
  <Dependencies />
  <Assets>
    <Asset Type="Microsoft.VisualStudio.Code.Manifest" Path="extension/package.json"
           Addressable="true" />
  </Assets>
</PackageManifest>
"""
    types = """<?xml version="1.0" encoding="utf-8"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension=".json" ContentType="application/json" />
  <Default Extension=".js" ContentType="application/javascript" />
  <Default Extension=".md" ContentType="text/markdown" />
  <Default Extension=".vsixmanifest" ContentType="text/xml" />
</Types>
"""
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("[Content_Types].xml", types)
        z.writestr("extension.vsixmanifest", manifest)
        for f in FILES:
            z.write(HERE / f, f"extension/{f}")
    return out


def sync_package() -> bool:
    """Set the language's file extensions in package.json to the packs' source suffixes;
    True if it changed."""
    path = HERE / "package.json"
    text = path.read_text()
    pkg = json.loads(text)
    lang = pkg["contributes"]["languages"][0]
    exts = source_extensions()
    if lang["extensions"] == exts:
        return False
    old = json.dumps(lang["extensions"])
    path.write_text(text.replace(f'"extensions": {old}', f'"extensions": {json.dumps(exts)}', 1))
    return True


def main() -> int:
    GRAMMAR.write_text(render_grammar())
    sync_package()
    pkg = json.loads((HERE / "package.json").read_text())
    out = vsix(HERE / f"{pkg['name']}-{pkg['version']}.vsix")
    print(f"wrote {GRAMMAR.relative_to(ROOT)} and {out.relative_to(ROOT)}")
    print(f"install: code --install-extension {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
