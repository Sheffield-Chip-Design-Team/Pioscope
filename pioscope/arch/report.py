"""Render the architecture study: `pioscope arch` prints it; `--write` writes
<pack docs>/arch-study.md."""

from __future__ import annotations

import argparse
from collections.abc import Sequence
from pathlib import Path

from .arch import Arch, load_archs
from .cost import OVERHEAD, Cost, area, load_cost
from .demand import Workload, load_workloads, unit_types
from .evaluate import (
    FAMILIES,
    FAMILY_TEXT,
    HEADROOM,
    HEADROOM_SWEEP,
    describe,
    minimal_all,
    ranking,
    score,
    sensitivity,
)
from .export import study_data
from .viz import out_path as page_path
from .viz import render as render_page


def out_path() -> Path:
    from pioscope.packs import active

    return active().docs / "arch-study.md"



def _pct(x: float) -> str:
    return f"{100 * x:.0f}%"


def _ge(x: float) -> str:
    return f"{x:,.0f}"


def _table(head: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head),
            *("| " + " | ".join(r) + " |" for r in rows), ""]


def _paths() -> tuple[str, str, str, str]:
    """(pack title, arch data dir, programs dir, docs/ relative to the output)."""
    import os

    from pioscope.packs import ROOT, active

    p = active()
    return (p.title, str(p.arch.relative_to(ROOT)), str(p.programs.relative_to(ROOT)),
            os.path.relpath(ROOT / "docs", p.docs))


def render(ws: Sequence[Workload], archs: Sequence[Arch], c: Cost) -> str:
    title, arch_dir, progs, docs = _paths()
    out = [
        "# Architecture study: PIO-style cores vs a software-allocated mesh (generated)",
        "",
        f"ISA pack: {title}. Generated by `uv run pioscope arch --write` from "
        f"`{arch_dir}/{{workloads,architectures,cost}}.yaml` and the programs in "
        f"`{progs}/`. Do not edit by hand. Method and "
        f"scope: [ADR-0007]({docs}/open_items/0007-architecture-study.md). Interactive view "
        "(architecture diagrams, utilisation heatmap, charts): open "
        "[arch-study.html](arch-study.html) in a browser. Terms, formulas and worked "
        f"examples: [arch-guide.md]({docs}/arch-guide.md).",
        "",
        "> **Status: analytic estimates.** Area constants are placeholders (see the "
        "sensitivity table). Activity figures are estimated from each program's static bit "
        "shares and a traffic load; they will be replaced by counters measured on the engine "
        "model. Allocation is static (load time) only. imem is flip-flops or IHP SRAM "
        "macros, whichever is cheaper for each configuration.",
        "",
    ]

    # ---- conclusion first: the ranking ------------------------------------------------
    sized = minimal_all(ws, c, HEADROOM)
    rank = ranking(ws, c, HEADROOM)
    out += ["## Smallest configuration of each family that fits every workload", "",
            f"With at least {HEADROOM} imem words provisioned per core "
            "(CLAUDE.md §3), on top of fitting the workloads.", ""]
    rows = []
    for f, tot in rank:
        a = sized[f]
        scores = [score(a, w, c) for w in ws]
        n = len(scores)
        rows.append([f"`{f}`", FAMILY_TEXT[f], describe(a), _ge(tot), f"{c.tiles(tot):.1f}",
                     _pct(scores[0].overhead),
                     _pct(sum(s.alloc_area for s in scores) / n),
                     _pct(sum(s.active_area for s in scores) / n)])
    out += _table(["family", "what it is", "smallest config", "area (GE)", "tiles",
                   "overhead", "mean allocated area", "mean active area"], rows)
    out += ["- **tiles:** Tiny Tapeout tiles covered by the cells and macros at 100% density; "
            "real placement needs more. A 64-word SRAM macro is 236.8 um wide, wider than one "
            "tile (about 202 um).",
            "- **overhead:** imem read ports, crossbar and allocation-config flops, as a "
            "share of total area.",
            "- **allocated area:** the share of the area that is assigned to some program in "
            "a workload. **Active area:** the same, weighted by how busy the logic is "
            "(storage counts when allocated). Means are over all workloads.", ""]

    out += ["### Area breakdown (GE)", ""]
    classes = ["core", "imem", "imem_read", "fifo", *(f"unit:{u}" for u in unit_types()),
               "xbar", "config"]
    rows = []
    for f, _ in rank:
        br = area(sized[f], c)
        rows.append([f"`{f}`", *(_ge(br.get(k, 0.0)) if br.get(k) else "-" for k in classes)])
    out += _table(["family", *classes], rows)

    # ---- imem provisioning: flops vs SRAM ---------------------------------------------
    out += ["## imem provisioning: flip-flops vs SRAM", "",
            "Area (GE) of each family's smallest configuration as the imem provisioned per "
            "Core grows, and which storage wins. 0 = just enough for the workloads.", ""]
    rows = []
    for h in HEADROOM_SWEEP:
        m = minimal_all(ws, c, h)
        rows.append([str(h), *(f"{_ge(sum(area(m[f], c).values()))} ({m[f].imem_tech})"
                               for f in FAMILIES)])
    out += _table(["words/core", *(f"`{f}`" for f in FAMILIES)], rows)

    # ---- per workload on the sized configs ---------------------------------------------
    out += ["## Utilisation per workload (smallest configs)", "",
            "Allocated share of cores / imem words / unit instances, and active area.", ""]
    rows = []
    for w in ws:
        row = [f"`{w.name}`"]
        for f in FAMILIES:
            s = score(sized[f], w, c)
            row.append(f"{_pct(s.alloc['cores'])} / {_pct(s.alloc['imem'])} / "
                       f"{_pct(s.alloc['units'])} · {_pct(s.active_area)}")
        rows.append(row)
    out += _table(["workload", *(f"`{f}`" for f in FAMILIES)], rows)

    # ---- hand-picked architectures -----------------------------------------------------
    out += ["## Hand-picked architectures", ""]
    rows = []
    for a in archs:
        rows.append([f"`{a.name}`", describe(a), _ge(sum(area(a, c).values()))])
    out += _table(["architecture", "configuration", "area (GE)"], rows)
    rows = []
    for w in ws:
        row = [f"`{w.name}`"]
        for a in archs:
            s = score(a, w, c)
            row.append(_pct(s.active_area) if s.feasible else f"does not fit: {s.reason}")
        rows.append(row)
    out += ["Active area per workload (or why it does not fit):", ""]
    out += _table(["workload", *(f"`{a.name}`" for a in archs)], rows)

    # ---- what a cheap allocator loses --------------------------------------------------
    out += ["## Exact vs greedy allocation", "",
            "The mesh allocator is the \"higher-level software\". With a full crossbar any "
            "assignment works; with clusters, first-fit can fail where an exact search "
            "succeeds.", ""]
    rows = []
    for a in [*archs, sized["mesh_c2"]]:
        if a.family != "mesh":
            continue
        lost = [w.name for w in ws
                if score(a, w, c).feasible and not score(a, w, c, exact=False).feasible]
        rows.append([f"`{a.name}`", ", ".join(f"`{n}`" for n in lost) or "none"])
    out += _table(["architecture", "workloads only the exact allocator fits"], rows)

    # ---- sensitivity -------------------------------------------------------------------
    base = [f for f, _ in rank]
    out += ["## Sensitivity to the area constants", "",
            f"Baseline order (smallest first): {' < '.join(f'`{f}`' for f in base)}. "
            "Each constant scaled x0.5 and x2 on its own:", ""]
    rows = []
    for sv in sensitivity(ws, c, HEADROOM):
        rows.append([f"`{sv.knob}`", " < ".join(sv.low), " < ".join(sv.high),
                     "**leader changes**" if sv.leader_changes
                     else ("order changes" if sv.flips else "stable")])
    out += _table(["constant", "order at x0.5", "order at x2", "effect"], rows)

    # ---- inputs ------------------------------------------------------------------------
    out += ["## Inputs", "", "### Workloads", ""]
    rows = [[f"`{w.name}`", w.description,
             ", ".join(f"{t.program} ({t.load:g})" for t in w.tasks),
             str(sum(t.demand.imem_words for t in w.tasks)), str(w.pads)] for w in ws]
    out += _table(["workload", "description", "programs (load)", "imem words", "pads"], rows)

    out += ["### Program demand", "",
            "Bit share: the share of a frame's bit-times each unit is busy (static estimate).",
            ""]
    demands = {t.program: t.demand for w in ws for t in w.tasks}
    rows = []
    for name, d in sorted(demands.items()):
        rows.append([f"`{name}`", str(d.imem_words),
                     ", ".join(f"{u} {d.bit_share[u]:.2f}" for u in sorted(d.units)) or "-",
                     f"{'tx' if d.fifo_tx else ''}{'+' if d.fifo_tx and d.fifo_rx else ''}"
                     f"{'rx' if d.fifo_rx else ''}" or "-",
                     str(d.pads), f"{d.bit_rate:g}" if d.bit_rate else "-"])
    out += _table(["program", "imem", "units (bit share)", "FIFOs", "pads", "bit rate"], rows)

    out += ["### Area constants (GE, placeholders)", ""]
    rows = [[k, f"{getattr(c, k):g}"] for k in
            ("flop_bit", "mux2_bit", "core", "fifo_control", "unit_port_bits", "config_bit")]
    rows += [[f"units.{u}", f"{c.units[u]:g}"] for u in unit_types()]
    out += _table(["constant", "value"], rows)
    out += [f"Overhead classes: {', '.join(OVERHEAD)}. GE per um^2: 1 / {c.nand2_um2:g} "
            "(sg13g2_nand2_1).", "", "### SRAM macros (IHP SG13G2 datasheets)", ""]
    rows = [[f"`{m.name}`", str(m.words), str(m.bits), str(m.ports), f"{m.um2:,.2f}",
             _ge(m.um2 / c.nand2_um2)] for m in c.sram]
    out += _table(["macro", "words", "bits", "ports", "area (um^2)", "area (GE)"], rows)
    return "\n".join(out)


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="pioscope arch",
        description="Architecture study: size and score PIO-style vs mesh engines on area and "
                    "utilisation (analytic estimates).")
    ap.add_argument("--workloads", type=Path, help="default: the active ISA pack's")
    ap.add_argument("--archs", type=Path, help="default: the active ISA pack's")
    ap.add_argument("--cost", type=Path, help="default: the active ISA pack's")
    ap.add_argument("--write", action="store_true",
                    help="write the pack's arch-study.md and interactive arch-study.html "
                         "instead of printing")
    ap.add_argument("--html", type=Path, metavar="PATH",
                    help="write only the interactive page, to PATH")
    a = ap.parse_args(argv)
    ws, archs, cost = load_workloads(a.workloads), load_archs(a.archs), load_cost(a.cost)
    if a.html or a.write:
        page = render_page(study_data(ws, archs, cost))
        dest = a.html or page_path()
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(page)
        print(f"wrote {dest}")
        if a.html:
            return 0
    text = render(ws, archs, cost)
    if a.write:
        out = out_path()
        out.write_text(text)
        print(f"wrote {out}")
    else:
        print(text)
    return 0
